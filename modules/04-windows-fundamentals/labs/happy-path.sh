#!/usr/bin/env bash
# CI lab-reproduction smoke test for Module 04 (Windows Fundamentals).
#
# Runs on a CLEAN machine with ONLY bash + coreutils -- NO PowerShell, NO Windows, NO network.
# It proves the GRC-relevant CORE LOGIC of the §6 lab: given the JSON compliance bundle that the
# PowerShell collector produces, the SOC 2 CC6 control EVALUATION maps each reading to PASS/FLAG
# correctly. The real §6 lab needs a live Windows endpoint to *collect* the bundle; this test
# proves the *evaluation* logic against committed sample bundles.
#
# Asserts, against two committed fixtures:
#   - NON-COMPLIANT bundle (generated by setup.sh): BitLocker != FullyEncrypted -> encryption FAIL;
#     Defender disabled -> protection FAIL; failed-logon count > threshold -> FLAG;
#     unexpected local admin present -> admin FAIL; overall verdict NON-COMPLIANT.
#   - COMPLIANT bundle (committed): BitLocker FullyEncrypted -> encryption PASS; Defender on & fresh
#     -> protection PASS; failed logons <= threshold -> no flag; only approved admin -> admin PASS;
#     overall verdict COMPLIANT.
# Exits 0 on success; non-zero with a clear FAIL message otherwise.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
cd "$WORK"

FAILED_LOGON_THRESHOLD=5
APPROVED_ADMIN_SUFFIX='\Administrator'   # only the built-in Administrator is approved here

# --- pure bash + coreutils JSON field readers (no jq dependency) -------------------------
# Read a scalar string/number/bool value for a top-level "Key": <value> pair.
json_scalar() {
  # $1 = file, $2 = key. Strips quotes/whitespace/trailing comma from the value.
  grep -E "\"$2\"[[:space:]]*:" "$1" \
    | head -n1 \
    | sed -E "s/.*\"$2\"[[:space:]]*:[[:space:]]*//; s/[[:space:]]*,?[[:space:]]*$//; s/^\"//; s/\"$//"
}

# Read the LocalAdmins array's contents (between [ and ]) as a single line for membership checks.
json_admins() {
  # $1 = file. Returns the raw bracketed list contents on one line.
  tr -d '\n' < "$1" \
    | sed -E 's/.*"Control_CC6_3_LocalAdmins"[[:space:]]*:[[:space:]]*\[//; s/\].*//'
}

# --- the SOC 2 CC6 control evaluation (the logic under test) -----------------------------
# Prints the overall verdict (COMPLIANT / NON-COMPLIANT) and exits the function with the
# per-control results available via the named globals it sets.
evaluate_bundle() {
  local f="$1"
  R_ENC="$(json_scalar "$f" Control_CC6_1_Encryption)"
  R_DEF="$(json_scalar "$f" Control_CC6_8_DefenderEnabled)"
  R_LOGONS="$(json_scalar "$f" Control_CC6_1_FailedLogonCount)"
  local admins; admins="$(json_admins "$f")"

  # CC6.1 encryption: pass iff FullyEncrypted.
  if [ "$R_ENC" = "FullyEncrypted" ]; then ENC_RESULT=PASS; else ENC_RESULT=FAIL; fi

  # CC6.8 endpoint protection: pass iff Defender enabled (true).
  if [ "$R_DEF" = "true" ]; then DEF_RESULT=PASS; else DEF_RESULT=FAIL; fi

  # CC6.1 failed logons: flag iff count exceeds threshold.
  if [ "$R_LOGONS" -gt "$FAILED_LOGON_THRESHOLD" ]; then LOGON_RESULT=FLAG; else LOGON_RESULT=OK; fi

  # CC6.3 local admins: pass iff every listed admin is the approved built-in Administrator.
  # Any member NOT ending in the approved suffix fails the control.
  ADMIN_RESULT=PASS
  local cleaned; cleaned="$(printf '%s' "$admins" | tr ',' '\n')"
  while IFS= read -r raw; do
    local m; m="$(printf '%s' "$raw" | sed -E 's/^[[:space:]]*"//; s/"[[:space:]]*$//')"
    [ -z "$m" ] && continue
    case "$m" in
      *"$APPROVED_ADMIN_SUFFIX") : ;;          # approved built-in admin
      *) ADMIN_RESULT=FAIL ;;                  # any other standing admin fails CC6.3
    esac
  done <<< "$cleaned"

  if [ "$ENC_RESULT" = PASS ] && [ "$DEF_RESULT" = PASS ] \
     && [ "$LOGON_RESULT" = OK ] && [ "$ADMIN_RESULT" = PASS ]; then
    VERDICT=COMPLIANT
  else
    VERDICT=NON-COMPLIANT
  fi
}

# --- fixture 1: NON-COMPLIANT (generated by setup.sh) ------------------------------------
bash "$HERE/setup.sh" "$WORK/lab04" >/dev/null
test -f lab04/endpoint-bundle.json || { echo "FAIL: setup did not create the sample bundle"; exit 1; }

evaluate_bundle "$WORK/lab04/endpoint-bundle.json"
[ "$ENC_RESULT"   = FAIL ] || { echo "FAIL: non-compliant fixture should fail encryption, got '$ENC_RESULT' (enc='$R_ENC')"; exit 1; }
[ "$DEF_RESULT"   = FAIL ] || { echo "FAIL: non-compliant fixture should fail Defender, got '$DEF_RESULT' (def='$R_DEF')"; exit 1; }
[ "$LOGON_RESULT" = FLAG ] || { echo "FAIL: non-compliant fixture should FLAG failed logons ($R_LOGONS > $FAILED_LOGON_THRESHOLD), got '$LOGON_RESULT'"; exit 1; }
[ "$ADMIN_RESULT" = FAIL ] || { echo "FAIL: non-compliant fixture should fail local-admin (rogue admin present), got '$ADMIN_RESULT'"; exit 1; }
[ "$VERDICT"      = NON-COMPLIANT ] || { echo "FAIL: non-compliant fixture overall verdict should be NON-COMPLIANT, got '$VERDICT'"; exit 1; }

# --- fixture 2: COMPLIANT (committed) ----------------------------------------------------
test -f "$HERE/sample-bundle-compliant.json" || { echo "FAIL: committed compliant fixture missing"; exit 1; }
evaluate_bundle "$HERE/sample-bundle-compliant.json"
[ "$ENC_RESULT"   = PASS ] || { echo "FAIL: compliant fixture should pass encryption, got '$ENC_RESULT' (enc='$R_ENC')"; exit 1; }
[ "$DEF_RESULT"   = PASS ] || { echo "FAIL: compliant fixture should pass Defender, got '$DEF_RESULT' (def='$R_DEF')"; exit 1; }
[ "$LOGON_RESULT" = OK ]   || { echo "FAIL: compliant fixture should NOT flag failed logons ($R_LOGONS <= $FAILED_LOGON_THRESHOLD), got '$LOGON_RESULT'"; exit 1; }
[ "$ADMIN_RESULT" = PASS ] || { echo "FAIL: compliant fixture should pass local-admin (only approved admin), got '$ADMIN_RESULT'"; exit 1; }
[ "$VERDICT"      = COMPLIANT ] || { echo "FAIL: compliant fixture overall verdict should be COMPLIANT, got '$VERDICT'"; exit 1; }

echo "PASS: Module 04 lab reproduces (CC6 evaluation correct on both fixtures: non-compliant->NON-COMPLIANT, compliant->COMPLIANT)"
