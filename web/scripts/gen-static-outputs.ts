#!/usr/bin/env bun
/**
 * Generates src/engines/shell/generated/static-outputs.ts from captured fixtures whose
 * command is a `--help` invocation (web ISA ISC-52: --help byte-matches captured output).
 *
 * Single source of truth: .ci/fixtures/captured/*.json. Run after re-capturing:
 *   bun run scripts/gen-static-outputs.ts
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";

const HERE = dirname(new URL(import.meta.url).pathname);
const CAPTURED = join(HERE, "../../.ci/fixtures/captured");
const OUT_FILE = join(HERE, "../src/engines/shell/generated/static-outputs.ts");

const entries: Record<string, { stdout: string; exit: number; source: string }> = {};
for (const file of readdirSync(CAPTURED).sort()) {
  if (!file.endsWith(".json")) continue;
  const fx = JSON.parse(readFileSync(join(CAPTURED, file), "utf8"));
  if (typeof fx.cmd !== "string" || !fx.cmd.endsWith("--help")) continue;
  entries[fx.cmd] = { stdout: fx.stdout ?? "", exit: fx.exit ?? 0, source: fx.id };
}

const lines: string[] = [
  "/**",
  " * AUTO-GENERATED by scripts/gen-static-outputs.ts — DO NOT EDIT.",
  " * Source of truth: .ci/fixtures/captured/*.json (--help captures).",
  " */",
  "",
  "export const STATIC_OUTPUTS: Record<string, { stdout: string; exit: number }> = {",
];
for (const [cmd, e] of Object.entries(entries)) {
  lines.push(`  // from fixture ${e.source}`);
  lines.push(`  ${JSON.stringify(cmd)}: { stdout: ${JSON.stringify(e.stdout)}, exit: ${e.exit} },`);
}
lines.push("};", "");

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, lines.join("\n"));
console.log(`wrote ${OUT_FILE} (${Object.keys(entries).length} static outputs)`);
