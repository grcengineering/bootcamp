/**
 * Module-02 golden/anti-transcript replay gate (root ISA ISC-73) — the admin-lab twin of
 * exercise-replay.test.ts. Module 02's exercise runs on the booted web-01 world (shell
 * engine + linuxadmin extension via `adminLab`), which the shared harness's vanilla
 * analyst@workstation session cannot construct — so the same contract is enforced here
 * with the engine's own session builder (helpers-m02, the fidelity suite's world):
 *   - replaying golden.jsonl must satisfy EVERY action task's verifiers
 *   - replaying each anti-*.jsonl must FAIL its targeted task (and name a gap)
 *   - every `from: generated` expectation is regenerated by the golden replay
 *     (file_content_equals passing IS the regeneration assertion; orphan keys rejected)
 */
import { describe, expect, test } from "bun:test";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { parse } from "yaml";
import { ExerciseSpecSchema, type ExerciseSpec } from "../src/lib/exercise-spec";
import { runCheck, type VerifyContext } from "../src/verifiers/registry";
import type { ShellSession } from "../src/engines/shell/types";
import { createM02Session } from "./helpers-m02";

const ROOT = join(dirname(new URL(import.meta.url).pathname), "../..");
const EXERCISES = join(ROOT, "modules/02-linux-system-fundamentals/exercises");
const TRANSCRIPTS = join(EXERCISES, "transcripts");

const spec: ExerciseSpec = ExerciseSpecSchema.parse(
  parse(readFileSync(join(EXERCISES, "exercise.yaml"), "utf8")),
);
const expectations: Record<string, string> = Object.fromEntries(
  Object.entries(
    JSON.parse(readFileSync(join(TRANSCRIPTS, "expectations.json"), "utf8")) as Record<string, string>,
  ).filter(([k]) => !k.startsWith("_")),
);

/** Feed one transcript input (dialogue/heredoc continuation lines separated by \n). */
function replayInput(session: ShellSession, input: string) {
  const [first, ...rest] = input.split("\n");
  let r = session.exec(first);
  for (const line of rest) {
    if (r.state !== "pending") break;
    r = session.feedStdin(line + "\n");
  }
  if (r.state === "pending") r = session.eof();
  return r;
}

function loadTranscript(path: string): { header: { anti_for?: string; reason?: string } | null; inputs: string[] } {
  const lines = readFileSync(path, "utf8").trim().split("\n").map((l) => JSON.parse(l));
  const header = lines[0]?.anti_for ? lines[0] : null;
  return { header, inputs: lines.filter((l) => l.input !== undefined).map((l) => l.input) };
}

function verifyAll(session: ShellSession) {
  const results: Record<string, { pass: boolean; gaps: string[] }> = {};
  for (const task of spec.tasks) {
    if (task.type !== "action") continue;
    const gaps: string[] = [];
    let pass = true;
    task.verify.forEach((chk, i) => {
      const ctx: VerifyContext = { expectations, expectationKey: `${task.id}:${i}` };
      const out = runCheck(session, chk as never, ctx);
      if (!out.pass) { pass = false; gaps.push(out.gap); }
    });
    results[task.id] = { pass, gaps };
  }
  return results;
}

describe("module-02 exercise replay (golden passes, anti fails its target)", () => {
  test("golden transcript satisfies every action task", () => {
    const session = createM02Session();
    const { inputs } = loadTranscript(join(TRANSCRIPTS, "golden.jsonl"));
    for (const input of inputs) replayInput(session, input);
    const results = verifyAll(session);
    for (const [taskId, r] of Object.entries(results)) {
      expect(`${taskId}: ${r.pass ? "pass" : r.gaps.join(" | ")}`).toBe(`${taskId}: pass`);
    }
  });

  test("golden replay regenerates every expectations.json value from engine state (ISC-60)", () => {
    const session = createM02Session();
    const { inputs } = loadTranscript(join(TRANSCRIPTS, "golden.jsonl"));
    for (const input of inputs) replayInput(session, input);
    // every generated expectation maps to a file_content_equals check in the spec, and the
    // engine-produced file content must equal the committed bootstrap value byte-for-byte
    // (modulo the registry's single-trailing-newline rule)
    const norm = (s: string) => s.replace(/\n$/, "");
    const byKey: Record<string, string> = {};
    spec.tasks.forEach((t) =>
      t.verify.forEach((chk, i) => {
        const c = chk as { check: string; path?: string; from?: string };
        if (c.from === "generated" && c.check === "file_content_equals" && c.path)
          byKey[`${t.id}:${i}`] = c.path;
      }),
    );
    expect(Object.keys(byKey).sort()).toEqual(Object.keys(expectations).sort()); // no orphan keys
    for (const [key, path] of Object.entries(byKey)) {
      const got = session.readFile(path);
      expect(got).not.toBeNull();
      expect(`${key}=${norm(got!)}`).toBe(`${key}=${norm(expectations[key])}`);
    }
  });

  for (const anti of readdirSync(TRANSCRIPTS).filter((f) => f.startsWith("anti-"))) {
    test(`${anti} fails its targeted task`, () => {
      const { header, inputs } = loadTranscript(join(TRANSCRIPTS, anti));
      expect(header?.anti_for).toBeTruthy();
      const session = createM02Session();
      for (const input of inputs) replayInput(session, input);
      const results = verifyAll(session);
      const target = results[header!.anti_for!];
      expect(target).toBeDefined();
      expect(target.pass).toBe(false);
      expect(target.gaps.join("")).not.toBe("");
    });
  }

  test("transcripts exist (suite is not vacuous)", () => {
    expect(existsSync(join(TRANSCRIPTS, "golden.jsonl"))).toBe(true);
    expect(readdirSync(TRANSCRIPTS).filter((f) => f.startsWith("anti-")).length).toBeGreaterThanOrEqual(2);
  });
});
