// Rot dashboard: continuous controls monitoring pointed at the curriculum itself.
// Reads every module meta.yaml and renders the curriculum's own compliance state
// (green = reviewed within cadence, amber = review due < 30d, red = overdue).
import { existsSync, readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { listModules, parseMetaYaml, rotStatus } from "../.ci/lib.ts";

const asOf = process.env.REVIEW_AS_OF ? new Date(process.env.REVIEW_AS_OF) : new Date();
const mods = listModules();

// Wave 2 (root ISA ISC-66): exercise presence + fixture age per module.
const capturedDir = join(import.meta.dir, "../.ci/fixtures/captured");
function exerciseCell(moduleDir: string): string {
  return existsSync(join(moduleDir, "exercises/exercise.yaml")) ? "🧪 yes" : "— none";
}
function fixtureAgeCell(moduleId: string): string {
  if (!existsSync(capturedDir)) return "—";
  const prefix = `m${moduleId.slice(0, 2)}-`;
  let newest: Date | null = null;
  for (const f of readdirSync(capturedDir)) {
    if (!f.startsWith(prefix) || !f.endsWith(".json")) continue;
    try {
      const fx = JSON.parse(readFileSync(join(capturedDir, f), "utf8"));
      const t = fx.provenance?.captured_at ? new Date(fx.provenance.captured_at) : null;
      if (t && (!newest || t > newest)) newest = t;
    } catch { /* unreadable fixture shows as missing age */ }
  }
  if (!newest) {
    // provenance may omit captured_at in v1 fixtures — fall back to presence count
    const n = readdirSync(capturedDir).filter((f) => f.startsWith(prefix)).length;
    return n ? `${n} fixtures` : "—";
  }
  const days = Math.floor((asOf.getTime() - newest.getTime()) / 86_400_000);
  return `${days}d old`;
}

let nRed = 0;
let nAmber = 0;
let nGreen = 0;
const rows: string[] = [];
for (const mod of mods) {
  const meta = existsSync(mod.metaYaml)
    ? parseMetaYaml(readFileSync(mod.metaYaml, "utf8"))
    : {};
  const reviewDue = typeof meta.review_due === "string" ? meta.review_due : undefined;
  const st = rotStatus(reviewDue, asOf);
  if (st.emoji === "🔴") nRed++;
  else if (st.emoji === "🟡") nAmber++;
  else if (st.emoji === "🟢") nGreen++;
  rows.push(
    `| ${st.emoji} | ${mod.id} | ${meta.owner ?? "—"} | ${meta.volatility ?? "—"} | ${meta.status ?? "—"} | ${meta.last_reviewed ?? "—"} | ${meta.review_due ?? "—"} | ${exerciseCell(mod.dir)} | ${fixtureAgeCell(mod.id)} | ${st.label} |`
  );
}

const out = [
  `# Curriculum Rot Dashboard`,
  ``,
  `> Continuous controls monitoring pointed at the curriculum itself. Generated by \`dashboard/generate.ts\` — do not edit by hand.`,
  `> As of **${asOf.toISOString().slice(0, 10)}** · 🟢 ${nGreen} green · 🟡 ${nAmber} amber · 🔴 ${nRed} red · ${mods.length} module(s) total`,
  ``,
  `| State | Module | Owner | Vol | Status | Last reviewed | Review due | Exercise | Fixtures | Δ |`,
  `|:--:|---|---|:--:|---|---|---|---|---|---|`,
  ...rows,
  ``,
  `*A 🔴 module is treated exactly like an overdue control — visible, owned, escalated. If the team can't keep their own training green, that is a live lesson in why controls rot.*`,
  ``,
].join("\n");

writeFileSync(join(import.meta.dir, "ROT-DASHBOARD.md"), out);
console.log(out);
console.error(
  `dashboard: wrote dashboard/ROT-DASHBOARD.md — ${mods.length} module(s) (🟢${nGreen} 🟡${nAmber} 🔴${nRed})`
);
